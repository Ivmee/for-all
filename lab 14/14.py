import pandas as pd
import math
import numpy as np

eta = 0.00001876  # кг/(м*с) - вязкость воздуха
rho1 = 1.184  # кг/м^3 - плотность воздуха
rho2 = 871.0  # кг/м^3 - плотность масла
g = 9.81  # м/с^2 - ускорение свободного падения
p = 1014.0  # гПа - давление воздуха
b = 0.000088  # мкм*гПа - параметр поправки (в метрах)
d = 0.003  # м - расстояние между обкладками конденсатора
s = 0.001  # м - расстояние между отметками на окуляре микроскопа

# Результаты прямых измерений
data = {
    't1': [19.817, 12.813, 12.145, 5.486, 13.185, 10.410, 6.629, 3.431, 9.347, 0.0],  # Время подъема (с)
    't2': [1.151, 10.650, 14.115, 4.438, 12.120, 5.056, 12.761, 3.025, 10.973, 0.0],  # Время опускания (с)
    'U': [370.0, 311.0, 105.0, 456.2, 119.2, 219.5, 600.0, 591.4, 595.7, 0.0]  # Напряжение (В)
}
df = pd.DataFrame(data)

# Обработка данных: вычисление скоростей
df['v1'] = s / df['t1']  # Скорость подъема (м/с)
df['v2'] = s / df['t2']  # Скорость опускания (м/с)

# Функция для вычисления радиуса капли (r0)
def calculate_r0(v2):
    return np.sqrt((9 * eta * v2) / (2 * (rho2 - rho1) * g))

# Функция для вычисления заряда капли (q0)
def calculate_q0(v1, v2, r0, U):
    return (6 * np.pi * eta * d * (v1 + v2) * r0) / U

# Вычисление r0 и q0
df['r0'] = df['v2'].apply(calculate_r0)
df['q0'] = df.apply(lambda row: calculate_q0(row['v1'], row['v2'], row['r0'], row['U']), axis=1)

# Функция для вычисления поправки Стокса (A)
def calculate_A(p):
    b_meters = b * 0.000001  # convert мкм*гПа to m* гПа
    return b_meters / p

# Вычисляем A ОДИН РАЗ, так как A не зависит от номера строки
A = calculate_A(p)

# Функция для вычисления скорректированного радиуса
def calculate_r_corrected(r0, A):
    return r0 / (1 + A / r0)

# Функция для вычисления скорректированного заряда
def calculate_q_corrected(q0, A, r0):
    return q0 / (1 + A / r0)**(3/2)

# Вычисление скорректированных значений (используем ОДНО значение A)
df['r_corrected'] = df.apply(lambda row: calculate_r_corrected(row['r0'], A), axis=1)
df['q_corrected'] = df.apply(lambda row: calculate_q_corrected(row['q0'], A, row['r0']), axis=1)

print("Результаты вычислений (первые несколько строк):")
print(df.head().to_string(formatters={
    'v1': '{:.8f}'.format,
    'v2': '{:.8f}'.format,
    'r0': '{:.8f}'.format,
    'q0': '{:.8e}'.format, 
    'r_corrected': '{:.8f}'.format,
    'q_corrected': '{:.8e}'.format
}))